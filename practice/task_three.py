# Написать программу, которая:
# Читает строки до ввода exit
# Сохраняет все непустые строки в список
# После exit:
# печатает количество строк
# печатает все сохранённые строки в обратном порядке
# Пример

# Ввод:
# hello

# world
# 123
# exit

# Вывод:
# Количество строк: 3
# 123
# world
# hello

# Ограничения
# использовать while
# использовать список
